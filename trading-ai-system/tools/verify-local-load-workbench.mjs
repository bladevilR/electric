import {chromium} from 'playwright';
import {mkdir,writeFile} from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const base=process.argv[2] || 'http://127.0.0.1:5301';
const output=path.resolve(process.argv[3] || 'output/load-repair-20260904');
await mkdir(output,{recursive:true});
const report=await fetch(`${base}/api/forecast/load?date=2026-09-04`).then(r=>r.json());
assert.equal(report.coverage.dateCount,214);
assert.equal(report.status,'stale_history');
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1600,height:1050},deviceScaleFactor:1});
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
try {
 await page.goto(`${base}/?view=data-sources&v=real-load-20260904`);
 await page.getByRole('tab',{name:'负荷预测',exact:true}).click();
 await page.locator('[data-result-preview] [data-foundation-action="open-load-backtest"]').click();
 await page.waitForFunction(date=>document.querySelector('[data-foundation-date]')?.value===date && document.querySelector('.foundation-forecast polyline[data-series-role="forecast"]')?.getAttribute('points')?.split(' ').length===96,report.latestComparableDate);
 assert.equal(await page.locator('.foundation-forecast polyline[data-series-role="actual"]').getAttribute('points').then(s=>s.split(' ').length),96);
 await page.screenshot({path:path.join(output,'01-real-load-backtest.png'),fullPage:true});
 await page.screenshot({path:path.join(output,'07-load-workbench-viewport.png')});
 await page.locator('[data-history-filter="field"]').selectOption('actualAverageLoadMw');
 await page.waitForFunction(()=>document.querySelectorAll('.foundation-history-table tbody tr').length===96);
 assert.equal(await page.locator('[data-history-filter="from"]').inputValue(),report.latestComparableDate);
 assert.equal(await page.locator('.foundation-history-table tbody tr').first().locator('td').nth(3).innerText(),'39.348 兆瓦（用电功率）');
 await page.locator('.foundation-history').screenshot({path:path.join(output,'02-real-load-history.png')});
 await page.getByRole('button',{name:'曲线',exact:true}).click();
 await page.locator('.foundation-history-charts polyline').waitFor();
 assert.equal(await page.locator('.foundation-history-charts polyline').getAttribute('points').then(s=>s.split(' ').length),96);
 await page.locator('.foundation-history').screenshot({path:path.join(output,'03-history-curve.png')});
 await page.getByRole('button',{name:'来源说明',exact:true}).click();
 await page.getByText('每 15 分钟的电量（千瓦时）÷ 250，得到该时段的平均用电功率（兆瓦）。',{exact:true}).first().waitFor();
 await page.locator('.foundation-history').screenshot({path:path.join(output,'04-load-source-evidence.png')});
 await page.locator('[data-foundation-date]').fill(report.coverage.latestDate);
 await page.locator('[data-foundation-date]').dispatchEvent('change');
 await page.waitForFunction(date=>document.querySelector('[data-foundation-date]')?.value===date && document.querySelector('.foundation-forecast polyline[data-series-role="actual"]')?.getAttribute('points')?.split(' ').length===96,report.coverage.latestDate);
 await page.waitForFunction(()=>document.querySelector('.foundation-history-evidence')?.textContent.includes('customer_usage_96.csv'));
 assert.equal(await page.locator('.foundation-forecast polyline[data-series-role="forecast"]').count(),0);
 await page.screenshot({path:path.join(output,'05-latest-actual-load.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:path.join(output,'06-load-mobile.png'),fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
 assert.deepEqual(errors,[]);
 const comparable=await fetch(`${base}/api/forecast/load?date=${report.latestComparableDate}`).then(r=>r.json());
 const summary={verifiedAt:new Date().toISOString(),dateCount:report.coverage.dateCount,actualPoints:report.coverage.dateCount*96,firstDate:report.coverage.earliestDate,lastDate:report.coverage.latestDate,backtestDate:report.latestComparableDate,backtestMetrics:comparable.metrics,checks:['history-table-96','history-curve-96','actual-forecast-overlay-96','source-file-hash-and-conversion','date-filters-persist','evidence-refreshes-with-date','stale-data-no-current-forecast','mobile-no-page-overflow','no-page-errors'],errors};
 await writeFile(path.join(output,'verification.json'),JSON.stringify(summary,null,2));
 console.log(JSON.stringify(summary,null,2));
} finally {await browser.close();}
